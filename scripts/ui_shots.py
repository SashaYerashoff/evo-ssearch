class Problems:
    """Collected findings, split into blocking errors and advisory warnings."""

    def __init__(self) -> None:
        self.errors: List[str] = []
        self.warnings: List[str] = []
        self.info: List[str] = []

    def error(self, message: str) -> None:
        self.errors.append(message)

    def warn(self, message: str) -> None:
        self.warnings.append(message)

    def note(self, message: str) -> None:
        self.info.append(message)

    def report(self, strict: bool) -> int:
        for message in self.info:
            print(f"ui shots: {message}")
        for message in self.warnings:
            print(f"ui shots WARN: {message}")
        for message in self.errors:
            print(f"ui shots ERROR: {message}")
        if self.errors:
            return 1
        if strict and self.warnings:
            print("ui shots: --strict, warnings are fatal")
            return 1
        print("ui shots check: OK")
        return 0


def _validate_step(step: Any, where: str, problems: Problems) -> None:
    if not isinstance(step, dict):
        problems.error(f"{where}: step must be an object, got {type(step).__name__}")
        return
    verbs = [key for key in step if key in STEP_VERBS]
    unknown = [key for key in step if key not in STEP_VERBS and not key.startswith("_")]
    if unknown:
        problems.error(f"{where}: unknown step verb(s) {unknown}; allowed: {sorted(STEP_VERBS)}")
    if len(verbs) != 1:
        problems.error(f"{where}: a step needs exactly one verb, found {verbs or 'none'}")
        return
    verb = verbs[0]
    value = step[verb]
    expected = STEP_VERBS[verb]
    if expected is int:
        if not isinstance(value, int) or isinstance(value, bool) or value < 0:
            problems.error(f"{where}: '{verb}' needs a non-negative integer")
        elif value > 30000:
            problems.warn(f"{where}: '{verb}' waits {value} ms; scenes should stay quick")
    elif expected is str:
        if not isinstance(value, str) or not value.strip():
            problems.error(f"{where}: '{verb}' needs a non-empty selector string")
    elif expected is dict:
        if not isinstance(value, dict):
            problems.error(f"{where}: '{verb}' needs an object")
            return
        required = {"fill": ("selector", "value"), "set_text": ("selector", "value"), "press": ("selector", "key")}[verb]
        for field in required:
            if not isinstance(value.get(field), str) or not value[field].strip():
                problems.error(f"{where}: '{verb}' needs a non-empty '{field}' string")


def _validate_scene(scene: Any, index: int, defaults: Dict[str, Any], seen_ids: set, seen_outputs: set,
                    problems: Problems) -> None:
    where = f"scene[{index}]"
    if not isinstance(scene, dict):
        problems.error(f"{where}: must be an object")
        return
    scene_id = scene.get("id")
    if not isinstance(scene_id, str) or not SCENE_ID_RE.match(scene_id):
        problems.error(f"{where}: 'id' must be kebab-case, got {scene_id!r}")
        return
    where = f"scene '{scene_id}'"
    if scene_id in seen_ids:
        problems.error(f"{where}: duplicate id")
    seen_ids.add(scene_id)

    if scene.get("ui") not in VALID_UIS:
        problems.error(f"{where}: 'ui' must be one of {sorted(VALID_UIS)}")
    if scene.get("auth", "none") not in VALID_ROLES:
        problems.error(f"{where}: 'auth' must be one of {sorted(VALID_ROLES)}")
    if not isinstance(scene.get("path"), str) or not scene["path"].startswith("/"):
        problems.error(f"{where}: 'path' must be a root-relative URL path")
    for field in ("title", "caption"):
        if not isinstance(scene.get(field), str) or not scene[field].strip():
            problems.error(f"{where}: '{field}' is required (the caption becomes the alt text)")

    policy = resolve(scene, defaults, "media_policy", "placeholder")
    if policy not in VALID_MEDIA_POLICIES:
        problems.error(f"{where}: 'media_policy' must be one of {sorted(VALID_MEDIA_POLICIES)}")

    output = scene.get("output")
    if not isinstance(output, str):
        problems.error(f"{where}: 'output' is required")
    else:
        if not output.startswith(ASSET_DIR_REL + "/") or not output.endswith(".png"):
            problems.error(f"{where}: 'output' must be a .png under {ASSET_DIR_REL}/")
        if output in seen_outputs:
            problems.error(f"{where}: duplicate output path {output}")
        seen_outputs.add(output)

    steps = scene.get("steps", [])
    if not isinstance(steps, list):
        problems.error(f"{where}: 'steps' must be an array")
    else:
        for step_index, step in enumerate(steps):
            _validate_step(step, f"{where} step[{step_index}]", problems)

    clip = scene.get("clip")
    if clip is not None and (not isinstance(clip, str) or not clip.strip()):
        problems.error(f"{where}: 'clip' must be null or a non-empty selector")

    used_by = scene.get("used_by", [])
    if not isinstance(used_by, list) or any(not isinstance(item, str) for item in used_by):
        problems.error(f"{where}: 'used_by' must be an array of doc paths")
    else:
        for doc in used_by:
            if not (REPO_ROOT / doc).is_file():
                problems.error(f"{where}: used_by references missing doc {doc}")


def scan_doc_image_references() -> Dict[str, List[str]]:
    """Map each committed asset path -> docs that embed it (markdown image syntax)."""
    references: Dict[str, List[str]] = {}
    for doc in sorted(DOC_ROOT.rglob("*.md")):
        try:
            text = doc.read_text(encoding="utf-8")
        except OSError:
            continue
        for match in MARKDOWN_IMAGE_RE.finditer(text):
            target = match.group(1).split("#")[0]
            if "ui/assets/" not in target:
                continue
            resolved = (doc.parent / target).resolve()
            try:
                rel = resolved.relative_to(REPO_ROOT).as_posix()
            except ValueError:
                rel = resolved.as_posix()
            references.setdefault(rel, []).append(doc.relative_to(REPO_ROOT).as_posix())
    return references


def _hash_path(path: Path) -> Optional[str]:
    digest = hashlib.sha256()
    if path.is_file():
        digest.update(path.read_bytes())
    elif path.is_dir():
        for child in sorted(path.rglob("*")):
            if child.is_file():
                digest.update(child.relative_to(path).as_posix().encode())
                digest.update(child.read_bytes())
    else:
        return None
    return digest.hexdigest()[:16]


def source_fingerprint(ui: str) -> Dict[str, Optional[str]]:
    return {rel: _hash_path(REPO_ROOT / rel) for rel in FINGERPRINT_SOURCES.get(ui, ())}


def sidecar_path(output_rel: str) -> Path:
    return REPO_ROOT / (output_rel + ".meta.json")


SELECTOR_TOKEN_RE = re.compile(r"[.#]([A-Za-z][\w-]*)")
HAS_TEXT_RE = re.compile(r":has-text\((['\"])(.*?)\1\)")


def selector_tokens(selector: str) -> List[str]:
    """Class and id names referenced by a selector, ignoring :has-text() literals."""
    return SELECTOR_TOKEN_RE.findall(HAS_TEXT_RE.sub("", selector))


def scene_selectors(scene: Dict[str, Any]) -> List[str]:
    selectors: List[str] = []
    clip = scene.get("clip")
    if isinstance(clip, str):
        selectors.append(clip)
    for step in scene.get("steps", []) or []:
        if not isinstance(step, dict):
            continue
        for verb in ("click", "wait_for", "hide", "scroll_to"):
            if isinstance(step.get(verb), str):
                selectors.append(step[verb])
        for verb in ("fill", "set_text", "press"):
            payload = step.get(verb)
            if isinstance(payload, dict) and isinstance(payload.get("selector"), str):
                selectors.append(payload["selector"])
    return selectors


def ui_source_text(ui: str) -> str:
    """Concatenated UI sources, used to sanity-check that a selector's names exist."""
    chunks: List[str] = []
    for rel in FINGERPRINT_SOURCES.get(ui, ()):
        path = REPO_ROOT / rel
        if path.is_file():
            chunks.append(path.read_text(encoding="utf-8", errors="ignore"))
        elif path.is_dir():
            for child in sorted(path.rglob("*")):
                if child.is_file() and child.suffix in {".tsx", ".ts", ".jsx", ".js", ".html", ".css"}:
                    chunks.append(child.read_text(encoding="utf-8", errors="ignore"))
    return "\n".join(chunks)


def lint_selectors(manifest: Dict[str, Any], problems: Problems) -> None:
    """Warn about class/id names no UI source mentions — a typo caught without a browser.

    Only a spelling check: a name that exists somewhere may still be the wrong
    element, and a name assembled at runtime may be missed. It is cheap and it
    catches the mistake that would otherwise waste a whole capture session.
    """
    cache: Dict[str, str] = {}
    for scene in manifest["scenes"]:
        ui = scene.get("ui")
        if ui not in FINGERPRINT_SOURCES:
            continue
        if ui not in cache:
            cache[ui] = ui_source_text(ui)
        source = cache[ui]
        if not source:
            continue
        unknown = sorted({
            token
            for selector in scene_selectors(scene)
            for token in selector_tokens(selector)
            if not re.search(rf"\b{re.escape(token)}\b", source)
        })
        if unknown:
            problems.warn(
                f"scene '{scene.get('id')}': no {ui} source mentions {', '.join(unknown)}"
            )


def validate(manifest: Dict[str, Any], strict: bool = False) -> int:
    problems = Problems()
    defaults = scene_defaults(manifest)
    seen_ids: set = set()
    seen_outputs: set = set()

    for index, scene in enumerate(manifest["scenes"]):
        _validate_scene(scene, index, defaults, seen_ids, seen_outputs, problems)

    lint_selectors(manifest, problems)

    references = scan_doc_image_references()
    for target, docs in sorted(references.items()):
        if not (REPO_ROOT / target).is_file():
            problems.error(f"{docs[0]} embeds missing screenshot {target} (run: ui_shots.py capture)")
        elif target not in seen_outputs:
            problems.error(f"{docs[0]} embeds {target}, which no scene in docs/ui/shots.json produces")

    asset_dir = REPO_ROOT / ASSET_DIR_REL
    if asset_dir.is_dir():
        for png in sorted(asset_dir.glob("*.png")):
            rel = png.relative_to(REPO_ROOT).as_posix()
            if rel not in seen_outputs:
                problems.error(f"orphan screenshot {rel}: no scene produces it (delete it or add a scene)")

    pending: List[str] = []
    for scene in manifest["scenes"]:
        output = scene.get("output")
        if not isinstance(output, str):
            continue
        if not scene.get("enabled", True):
            continue
        path = REPO_ROOT / output
        if not path.is_file():
            pending.append(scene.get("id", output))
            continue
        if output not in references:
            problems.warn(f"{output} is captured but no doc embeds it yet")
        meta_path = sidecar_path(output)
        if not meta_path.is_file():
            problems.warn(f"{output} has no {meta_path.name}; recapture to record its provenance")
            continue
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            problems.error(f"{meta_path.name}: unreadable ({exc})")
            continue
        if meta.get("media_policy") == "pass":
            problems.warn(
                f"{output} was captured with media_policy=pass (real media); "
                "confirm the source streams are rights-cleared and non-personal"
            )
        current = source_fingerprint(scene.get("ui", "legacy"))
        recorded = meta.get("source_fingerprint") or {}
        changed = [key for key, value in current.items() if recorded.get(key) != value]
        if changed:
            problems.warn(f"{output} predates changes in {', '.join(changed)}; recapture the scene")

    if pending:
        problems.note(f"{len(pending)} scene(s) not captured yet: {', '.join(sorted(pending))}")

    disabled = [s.get("id") for s in manifest["scenes"] if not s.get("enabled", True)]
    if disabled:
        problems.note(f"{len(disabled)} scene(s) disabled: {', '.join(str(d) for d in disabled)}")

    return problems.report(strict)



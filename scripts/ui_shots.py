def load_manifest(path: Path = MANIFEST_PATH) -> Dict[str, Any]:
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ManifestError(f"cannot read manifest {path}: {exc}") from exc
    try:
        data = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ManifestError(f"{path} is not valid JSON: {exc}") from exc
    if not isinstance(data, dict):
        raise ManifestError(f"{path} must contain a JSON object")
    if not isinstance(data.get("scenes"), list):
        raise ManifestError(f"{path} must contain a 'scenes' array")
    return data


def scene_defaults(manifest: Dict[str, Any]) -> Dict[str, Any]:
    defaults = manifest.get("defaults") or {}
    return defaults if isinstance(defaults, dict) else {}


def resolve(scene: Dict[str, Any], defaults: Dict[str, Any], key: str, fallback: Any = None) -> Any:
    if key in scene:
        return scene[key]
    return defaults.get(key, fallback)


def enabled_scenes(manifest: Dict[str, Any]) -> List[Dict[str, Any]]:
    return [s for s in manifest["scenes"] if s.get("enabled", True)]



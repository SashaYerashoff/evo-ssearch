def cmd_list(manifest: Dict[str, Any]) -> int:
    defaults = scene_defaults(manifest)
    for scene in manifest["scenes"]:
        state = "" if scene.get("enabled", True) else "  [disabled]"
        captured = "captured" if (REPO_ROOT / scene.get("output", "")).is_file() else "pending"
        print(
            f"{scene.get('id'):<32} {scene.get('ui'):<7} auth={scene.get('auth', 'none'):<9} "
            f"media={resolve(scene, defaults, 'media_policy', 'placeholder'):<12} {captured}{state}"
        )
    return 0


def cmd_snippet(manifest: Dict[str, Any], scene_id: str, doc: Optional[str]) -> int:
    """Print the markdown to paste into a guide, with the path relative to that guide."""
    scenes = {scene["id"]: scene for scene in manifest["scenes"] if isinstance(scene.get("id"), str)}
    scene = scenes.get(scene_id)
    if scene is None:
        print(f"ui shots: unknown scene '{scene_id}'", file=sys.stderr)
        return 2
    output = scene["output"]
    docs = [doc] if doc else (scene.get("used_by") or [])
    if not docs:
        print(f"![{scene['caption']}]({output})")
        return 0
    for target in docs:
        base = (REPO_ROOT / target).parent
        relative = os.path.relpath(REPO_ROOT / output, base)
        print(f"# {target}")
        print(f"![{scene['caption']}]({relative})")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", type=Path, default=MANIFEST_PATH)
    subparsers = parser.add_subparsers(dest="command", required=True)

    validate_parser = subparsers.add_parser("validate", help="check the manifest and committed assets (no browser)")
    validate_parser.add_argument("--strict", action="store_true", help="treat warnings as failures")

    subparsers.add_parser("list", help="list scenes and their capture state")

    snippet_parser = subparsers.add_parser("snippet", help="print the markdown embed for a scene")
    snippet_parser.add_argument("scene")
    snippet_parser.add_argument("--doc", default=None, help="target doc (default: the scene's used_by list)")

    capture_parser = subparsers.add_parser("capture", help="drive a running EVA and write screenshots")
    capture_parser.add_argument("--scene", action="append", default=[], help="scene id (repeatable)")
    capture_parser.add_argument(
        "--base-url",
        default=os.getenv("EVA_SHOTS_BASE_URL", "http://127.0.0.1:5000"),
        help="running EVA instance (default: $EVA_SHOTS_BASE_URL or http://127.0.0.1:5000)",
    )
    capture_parser.add_argument("--out-dir", type=Path, default=None,
                                help="write elsewhere than docs/ui/assets (smoke runs; skips sidecars)")
    capture_parser.add_argument("--check", action="store_true",
                                help="compare against committed screenshots instead of writing")
    capture_parser.add_argument("--check-tolerance", type=float, default=0.002,
                                help="fraction of pixels that may differ before --check calls a shot stale")
    capture_parser.add_argument("--allow-real-media", action="store_true",
                                help="permit media_policy=pass scenes (rights-cleared, non-personal streams only)")
    capture_parser.add_argument("--verify-tls", action="store_true", help="verify TLS (off for dev self-signed certs)")
    capture_parser.add_argument("--headed", action="store_true", help="show the browser window")
    capture_parser.add_argument("--timeout-ms", type=int, default=20000)

    args = parser.parse_args(argv)

    try:
        manifest = load_manifest(args.manifest)
    except ManifestError as exc:
        print(f"ui shots ERROR: {exc}", file=sys.stderr)
        return 1

    if args.command == "validate":
        return validate(manifest, strict=args.strict)
    if args.command == "list":
        return cmd_list(manifest)
    if args.command == "snippet":
        return cmd_snippet(manifest, args.scene, args.doc)
    if args.command == "capture":
        rc = validate(manifest, strict=False)
        if rc != 0:
            print("ui shots: fix the manifest before capturing", file=sys.stderr)
            return rc
        return capture(
            manifest,
            scene_ids=args.scene,
            base_url=args.base_url,
            out_dir=args.out_dir,
            check=args.check,
            allow_real_media=args.allow_real_media,
            verify_tls=args.verify_tls,
            headed=args.headed,
            timeout_ms=args.timeout_ms,
            check_tolerance=args.check_tolerance,
        )
    parser.error(f"unknown command {args.command}")
    return 2


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Capture and validate the UI screenshots used by the operator/admin guides.

Every screenshot under `docs/ui/assets/` is produced from a scene declared in
`docs/ui/shots.json` — no hand-taken screenshots, so a guide picture can always
be regenerated by a person or an assistant without guessing what was clicked.

Two halves with very different requirements:

  validate / list   stdlib only, no browser, no network, no running service.
                    This is the CI gate (called from scripts/check_docs_drift.sh).
  capture           needs requirements-docs.txt (Playwright) and a running EVA.
                    Workstation-only; the appliance never ships a browser driver.

Privacy: evidence frames are operational camera data and must never land in a
committed PNG. The default `media_policy` is `placeholder`, which intercepts the
evidence-image endpoints in the browser so real pixels are never decoded, and
additionally blurs elements the network layer cannot neutralize (video/canvas).
`pass` (real media, no redaction) exists for a deployment running deliberately
neutral streams and requires an explicit --allow-real-media flag; the choice is
recorded in each screenshot's sidecar so review can see it.

Usage:
    python scripts/ui_shots.py validate
    python scripts/ui_shots.py list
    python scripts/ui_shots.py capture --base-url http://127.0.0.1:5000
    python scripts/ui_shots.py capture --scene legacy-video-tab --check
"""

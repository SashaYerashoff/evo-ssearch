def credentials_for(role: str) -> Optional[Tuple[str, str]]:
    if role == "none":
        return None
    prefix = f"EVA_SHOTS_{role.upper()}_"
    user = os.getenv(prefix + "USER") or os.getenv("EVA_SHOTS_USER")
    password = os.getenv(prefix + "PASSWORD") or os.getenv("EVA_SHOTS_PASSWORD")
    if user and password:
        return user, password
    return None


def login_cookies(base_url: str, username: str, password: str, verify_tls: bool) -> List[Dict[str, Any]]:
    """Authenticate over the same POST /auth/login the UI uses, return browser cookies."""
    import requests  # already a runtime dependency; imported lazily for the stdlib-only paths
    import urllib3

    if not verify_tls:
        urllib3.disable_warnings(urllib3.exceptions.InsecureRequestWarning)
    session = requests.Session()
    session.verify = verify_tls
    response = session.post(
        base_url.rstrip("/") + "/auth/login",
        json={"username": username, "password": password},
        timeout=30,
    )
    response.raise_for_status()

    from urllib.parse import urlparse

    host = urlparse(base_url).hostname or "127.0.0.1"
    cookies = []
    for cookie in session.cookies:
        cookies.append(
            {
                "name": cookie.name,
                "value": cookie.value,
                "domain": cookie.domain or host,
                "path": cookie.path or "/",
                "httpOnly": bool(cookie.has_nonstandard_attr("HttpOnly")),
                "secure": bool(cookie.secure),
            }
        )
    return cookies


def redaction_css(scene: Dict[str, Any], defaults: Dict[str, Any], policy: str) -> str:
    always = list(resolve(scene, defaults, "redact_always", []) or [])
    extra = list(scene.get("redact_extra", []) or [])
    if policy == "pass":
        return ""
    selectors = always + extra
    if policy == "blur":
        selectors += list(resolve(scene, defaults, "redact", []) or [])
    selectors = [s for s in selectors if isinstance(s, str) and s.strip()]
    if not selectors:
        return ""
    joined = ",\n".join(selectors)
    return (
        f"{joined} {{\n"
        "  filter: blur(24px) grayscale(0.92) !important;\n"
        "  background-image: none !important;\n"
        "}\n"
    )


def _run_steps(page: Any, steps: Sequence[Dict[str, Any]], timeout_ms: int) -> None:
    for step in steps:
        if "click" in step:
            page.locator(step["click"]).first.click(timeout=timeout_ms)
        elif "wait_for" in step:
            page.locator(step["wait_for"]).first.wait_for(state="visible", timeout=timeout_ms)
        elif "wait_ms" in step:
            page.wait_for_timeout(step["wait_ms"])
        elif "hide" in step:
            page.eval_on_selector_all(
                step["hide"], "els => els.forEach(el => { el.style.visibility = 'hidden'; })"
            )
        elif "scroll_to" in step:
            page.locator(step["scroll_to"]).first.scroll_into_view_if_needed(timeout=timeout_ms)
        elif "fill" in step:
            page.locator(step["fill"]["selector"]).first.fill(step["fill"]["value"], timeout=timeout_ms)
        elif "set_text" in step:
            page.eval_on_selector_all(
                step["set_text"]["selector"],
                "(els, value) => els.forEach(el => { el.textContent = value; })",
                step["set_text"]["value"],
            )
        elif "press" in step:
            page.locator(step["press"]["selector"]).first.press(step["press"]["key"], timeout=timeout_ms)


def compare_png(existing: Path, candidate: Path) -> Tuple[float, str]:
    """Return (fraction of changed pixels, human summary).

    Font hinting and antialiasing move a handful of pixels between otherwise
    identical renders, so callers apply a tolerance instead of demanding an exact
    match. Without Pillow there is no pixel view, so any byte difference counts
    as a full change.
    """
    if existing.read_bytes() == candidate.read_bytes():
        return 0.0, "identical"
    try:
        from PIL import Image, ImageChops
    except ImportError:
        return 1.0, "bytes differ (install pillow for a pixel diff)"
    with Image.open(existing) as before, Image.open(candidate) as after:
        if before.size != after.size:
            return 1.0, f"size {before.size} -> {after.size}"
        diff = ImageChops.difference(before.convert("RGB"), after.convert("RGB"))
        bbox = diff.getbbox()
        if bbox is None:
            return 0.0, "pixel-identical"
        histogram = diff.convert("L").histogram()
        total = sum(histogram)
        changed = total - histogram[0]
        fraction = changed / total if total else 0.0
        return fraction, f"{fraction:.2%} of pixels changed, bbox {bbox}"


def capture(manifest: Dict[str, Any], scene_ids: Sequence[str], base_url: str, out_dir: Optional[Path],
            check: bool, allow_real_media: bool, verify_tls: bool, headed: bool, timeout_ms: int,
            check_tolerance: float = 0.002) -> int:
    defaults = scene_defaults(manifest)
    scenes = enabled_scenes(manifest)
    if scene_ids:
        wanted = set(scene_ids)
        unknown = wanted - {s["id"] for s in manifest["scenes"]}
        if unknown:
            print(f"ui shots: unknown scene(s): {', '.join(sorted(unknown))}", file=sys.stderr)
            return 2
        scenes = [s for s in manifest["scenes"] if s["id"] in wanted]
    if not scenes:
        print("ui shots: nothing to capture")
        return 0

    for scene in scenes:
        if resolve(scene, defaults, "media_policy", "placeholder") == "pass" and not allow_real_media:
            print(
                f"ui shots: scene '{scene['id']}' asks for media_policy=pass; "
                "re-run with --allow-real-media only when the source streams are rights-cleared "
                "and contain no personal data",
                file=sys.stderr,
            )
            return 2

    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print(
            "ui shots: playwright is not installed.\n"
            "  uv pip install --python .venv/bin/python -r requirements-docs.txt\n"
            "  .venv/bin/python -m playwright install chromium",
            file=sys.stderr,
        )
        return 2

    app_version = ""
    version_file = REPO_ROOT / "VERSION"
    if version_file.is_file():
        app_version = version_file.read_text(encoding="utf-8").strip()

    cookie_cache: Dict[str, List[Dict[str, Any]]] = {}
    failures: List[str] = []
    differences: List[str] = []
    written: List[str] = []

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=not headed)
        try:
            for scene in scenes:
                scene_id = scene["id"]
                role = scene.get("auth", "none")
                policy = resolve(scene, defaults, "media_policy", "placeholder")
                viewport = resolve(scene, defaults, "viewport", {"width": 1600, "height": 1000})

                if role != "none" and role not in cookie_cache:
                    creds = credentials_for(role)
                    if creds is None:
                        failures.append(
                            f"{scene_id}: no credentials for role '{role}' "
                            f"(set EVA_SHOTS_{role.upper()}_USER / _PASSWORD)"
                        )
                        continue
                    try:
                        cookie_cache[role] = login_cookies(base_url, creds[0], creds[1], verify_tls)
                    except Exception as exc:  # noqa: BLE001 - report, keep going with other scenes
                        failures.append(f"{scene_id}: login as '{role}' failed: {exc}")
                        continue

                context = browser.new_context(
                    viewport={"width": int(viewport["width"]), "height": int(viewport["height"])},
                    device_scale_factor=float(resolve(scene, defaults, "device_scale_factor", 1)),
                    color_scheme=resolve(scene, defaults, "color_scheme", "dark"),
                    locale=resolve(scene, defaults, "locale", "en-US"),
                    ignore_https_errors=not verify_tls,
                    reduced_motion="reduce",
                )
                try:
                    if role != "none":
                        context.add_cookies(cookie_cache[role])

                    seeds = resolve(scene, defaults, "local_storage", {}) or {}
                    if seeds:
                        # add_init_script takes no arguments, so the values are inlined as JSON.
                        context.add_init_script(
                            "for (const [k, v] of " + json.dumps(list(seeds.items())) + ") {"
                            " try { window.localStorage.setItem(k, v); } catch (e) {} }"
                        )

                    if policy == "placeholder":
                        def serve_placeholder(route: Any) -> None:
                            route.fulfill(status=200, content_type="image/svg+xml", body=PLACEHOLDER_SVG)

                        for pattern in EVIDENCE_URL_PATTERNS:
                            context.route(pattern, serve_placeholder)

                    page = context.new_page()
                    page.goto(base_url.rstrip("/") + scene["path"], wait_until="domcontentloaded",
                              timeout=timeout_ms)
                    _run_steps(page, scene.get("steps", []), timeout_ms)

                    page.add_style_tag(content=DETERMINISM_CSS)
                    css = redaction_css(scene, defaults, policy)
                    if css:
                        page.add_style_tag(content=css)
                    page.wait_for_timeout(int(resolve(scene, defaults, "settle_ms", 1500)))

                    output_rel = scene["output"]
                    target = (out_dir / Path(output_rel).name) if out_dir else (REPO_ROOT / output_rel)
                    target.parent.mkdir(parents=True, exist_ok=True)

                    if check:
                        import tempfile

                        with tempfile.TemporaryDirectory() as tmp:
                            candidate = Path(tmp) / "candidate.png"
                            _shoot(page, scene, candidate, timeout_ms)
                            if not target.is_file():
                                differences.append(f"{scene_id}: no committed screenshot at {output_rel}")
                            else:
                                fraction, summary = compare_png(target, candidate)
                                if fraction > check_tolerance:
                                    differences.append(f"{scene_id}: {summary}")
                                elif fraction > 0:
                                    print(f"ui shots: {scene_id} within tolerance ({summary})")
                        continue

                    _shoot(page, scene, target, timeout_ms)
                    written.append(scene_id)
                    if not out_dir:
                        meta = {
                            "scene": scene_id,
                            "tool": TOOL_ID,
                            "captured_at_utc": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
                            "app_version": app_version,
                            "ui": scene.get("ui"),
                            "auth_role": role,
                            "media_policy": policy,
                            "viewport": viewport,
                            "source_fingerprint": source_fingerprint(scene.get("ui", "legacy")),
                        }
                        sidecar_path(output_rel).write_text(
                            json.dumps(meta, indent=2, sort_keys=True) + "\n", encoding="utf-8"
                        )
                except Exception as exc:  # noqa: BLE001 - one broken scene must not abort the run
                    failures.append(f"{scene_id}: {type(exc).__name__}: {exc}")
                finally:
                    context.close()
        finally:
            browser.close()

    for scene_id in written:
        print(f"ui shots: captured {scene_id}")
    for message in differences:
        print(f"ui shots STALE: {message}")
    for message in failures:
        print(f"ui shots FAILED: {message}", file=sys.stderr)

    if failures:
        return 1
    if differences:
        print("ui shots: committed screenshots are out of date; re-run without --check")
        return 1
    print("ui shots: OK")
    return 0


def _shoot(page: Any, scene: Dict[str, Any], target: Path, timeout_ms: int) -> None:
    clip = scene.get("clip")
    if clip:
        page.locator(clip).first.screenshot(path=str(target), timeout=timeout_ms)
    else:
        page.screenshot(path=str(target))


